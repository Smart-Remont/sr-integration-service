"""Applications from the BI badge form and the list of BI Group residential complexes.

The rules of a lead live in ``crm.request_from_bi_badge``. Its refusal carries ``hint``: the kind
of refusal, and ``detail``: the form field. The general mapping of database errors keeps only the
text, so both are read here from the asyncpg error it keeps as the cause.

A database error can quote the name or the phone of the client, so the log gets the error type and
SQLSTATE, never the text.
"""

import json
import re
import time
from enum import StrEnum

from fastapi import status
from loguru import logger

from src.exceptions import InfrastructureError, StoredProcedureError

from .client_ip import hash_client_ip
from .errors import BiBadgeError
from .repo import BiBadgeRepository
from .schemas import BiBadgeLeadRequest, BiBadgeResident, FormValue

RESIDENTS_CACHE_SECONDS = 300

_UNAVAILABLE = "Форма временно недоступна. Напишите нам в WhatsApp"
_NOT_SENT = "Не удалось отправить заявку. Попробуйте ещё раз или напишите нам в WhatsApp"
# Generated by the page: a uuid. Anything else is dropped rather than refused, the field is hidden.
_DEVICE_ID_RE = re.compile(r"^[A-Za-z0-9-]{8,64}$")
_PAYLOAD_FIELDS = (
    "name",
    "phone",
    "ref",
    "resident_id",
    "resident_other",
    "area",
    "utm_source",
    "utm_medium",
    "utm_campaign",
    "utm_content",
    "utm_term",
    "lang",
)


class RefusalHint(StrEnum):
    VALIDATION = "BI_BADGE_VALIDATION"
    RATE_LIMIT = "BI_BADGE_RATE_LIMIT"


class ResidentCache:
    """The list changes a few times a year and the page asks for it on every open. Per worker."""

    def __init__(self, ttl_seconds: float) -> None:
        self.ttl_seconds = ttl_seconds
        self._residents: list[BiBadgeResident] | None = None
        self._loaded_at = 0.0

    def get(self) -> list[BiBadgeResident] | None:
        if self._residents is None or time.monotonic() - self._loaded_at > self.ttl_seconds:
            return None
        return self._residents

    def put(self, residents: list[BiBadgeResident]) -> None:
        self._residents = residents
        self._loaded_at = time.monotonic()

    def clear(self) -> None:
        self._residents = None


resident_cache = ResidentCache(RESIDENTS_CACHE_SECONDS)


class BiBadgeService:
    def __init__(
        self,
        repository: BiBadgeRepository,
        *,
        ip_secret: str,
        cache: ResidentCache = resident_cache,
    ) -> None:
        self.repository = repository
        self.ip_secret = ip_secret
        self.cache = cache

    async def residents(self) -> list[BiBadgeResident]:
        residents = self.cache.get()
        if residents is None:
            rows = await self.repository.resident_read()
            residents = [BiBadgeResident.model_validate(row) for row in rows]
            self.cache.put(residents)
        return residents

    async def create_lead(self, lead: BiBadgeLeadRequest, *, client_ip: str | None) -> None:
        if _is_filled(lead.website):
            # A bot gets the same answer as a person, so it has nothing to adapt to.
            logger.info("bi-badge lead: trap field filled, nothing created")
            return
        if not self.ip_secret:
            logger.error("bi-badge lead: BI_BADGE_IP_SECRET is not set")
            raise BiBadgeError(_UNAVAILABLE, status_code=status.HTTP_503_SERVICE_UNAVAILABLE)
        payload = _lead_payload(lead, ip_hash=hash_client_ip(client_ip, self.ip_secret))
        try:
            await self.repository.request_from_bi_badge(json.dumps(payload, ensure_ascii=False))
        except InfrastructureError as exc:
            raise _refusal(exc) from exc


def _lead_payload(lead: BiBadgeLeadRequest, *, ip_hash: str) -> dict[str, object]:
    payload: dict[str, object] = {}
    for field in _PAYLOAD_FIELDS:
        value = _cleaned(getattr(lead, field))
        if value is not None:
            payload[field] = value
    payload["ip_hash"] = ip_hash
    device_id = _cleaned(lead.device_id)
    if isinstance(device_id, str) and _DEVICE_ID_RE.fullmatch(device_id):
        payload["device_id"] = device_id
    return payload


def _cleaned(value: FormValue) -> FormValue:
    if isinstance(value, str):
        return value.strip() or None
    return value


def _is_filled(value: FormValue) -> bool:
    return _cleaned(value) is not None


def _refusal(exc: InfrastructureError) -> BiBadgeError:
    cause = exc.__cause__
    hint = getattr(cause, "hint", None)
    if isinstance(exc, StoredProcedureError) and hint == RefusalHint.VALIDATION:
        field = getattr(cause, "detail", None)
        logger.info("bi-badge lead: refused, field {field}", field=field)
        return BiBadgeError(
            exc.message,
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            field=field,
        )
    if isinstance(exc, StoredProcedureError) and hint == RefusalHint.RATE_LIMIT:
        logger.warning("bi-badge lead: limit of applications reached")
        return BiBadgeError(exc.message, status_code=status.HTTP_429_TOO_MANY_REQUESTS)
    logger.error(
        "bi-badge lead: database error {error}, state {state}",
        error=type(exc).__name__,
        state=getattr(cause, "sqlstate", None),
    )
    return BiBadgeError(_NOT_SENT, status_code=status.HTTP_500_INTERNAL_SERVER_ERROR)
